const { chromium } = require("playwright");
(async()=>{const b=await chromium.launch();const errs=[];
const c=await b.newContext({viewport:{width:390,height:800}});const p=await c.newPage();p.on("pageerror",e=>errs.push(e.message));
await p.goto("http://localhost:8766/index.html");
console.log("guide tab present:",(await p.$$("#tabs button[data-d='guide']")).length);
await p.click("#tabs button[data-d='guide']");
console.log("title:",(await p.textContent(".theme")).trim());
console.log("no intro box:",(await p.$$(".gnote")).length===0);
console.log("stops:",(await p.$$(".gstop")).length,"(expect 5)");
const hrefs=await p.$$eval(".gp a",a=>a.map(x=>x.href));
console.log("map links:",hrefs.length,"| all google maps:",hrefs.every(h=>h.startsWith("https://www.google.com/maps/search/?api=1&query=")));
const txt=await p.textContent("#list");
console.log("only village content:",!/Choirokoitia|Kato Drys|Zygi|Vavla|Jar Jams|Loula/.test(txt));
console.log("tab selected:",await p.$eval("#tabs button[data-d='guide']",e=>e.classList.contains("sel")));
await p.click("#tabs button[data-d='3']");
const day3=await p.$$eval(".item h3",h=>h.map(x=>x.textContent));
console.log("day 3 has olive farm:",day3.some(t=>t.includes("Terra Oliva")),"| viewpoint:",day3.some(t=>t.includes("תצפית")));
console.log("day 3 order ok:",day3.findIndex(t=>t.includes("Terra Oliva"))>day3.findIndex(t=>t.includes("Iason"))&&day3.findIndex(t=>t.includes("תצפית"))<day3.findIndex(t=>t.includes("מנוחה")));
console.log("errors:",JSON.stringify(errs));await b.close();})();
