const { chromium } = require("playwright");
(async()=>{const b=await chromium.launch();const errs=[];
const c=await b.newContext({viewport:{width:390,height:800}});const p=await c.newPage();p.on("pageerror",e=>errs.push(e.message));
await p.route("https://api.frankfurter.dev/**",r=>r.fulfill({status:200,contentType:"application/json",headers:{"access-control-allow-origin":"*"},body:JSON.stringify({base:"EUR",date:"2026-12-01",rates:{ILS:4}})}));
await p.goto("http://localhost:8766/index.html");
console.log("calc tab present:",(await p.$$("#tabs button[data-d='calc']")).length);
await p.click("#tabs button[data-d='calc']");
await p.fill("#fxRate","4");await p.fill("#fxAmt","25.5");
const r1=await p.textContent("#fxRes");console.log("result 25.5*4:",r1);
if(!/102/.test(r1))errs.push("bad result "+r1);
await p.fill("#fxAmt","");console.log("empty:",await p.textContent("#fxRes"));
await p.fill("#fxAmt","10,5");await p.fill("#fxRate","3.5");const r2=await p.textContent("#fxRes");console.log("comma input:",r2);
if(!/36\.75/.test(r2))errs.push("bad comma "+r2);
await p.click("#fxUpd");await p.waitForFunction(()=>document.getElementById("fxNote").textContent.includes("עודכן"));
console.log("rate after update:",await p.inputValue("#fxRate"),"| result:",await p.textContent("#fxRes"));
if(!/42/.test(await p.textContent("#fxRes")))errs.push("update not applied");
await p.reload();await p.click("#tabs button[data-d='calc']");console.log("rate saved:",await p.inputValue("#fxRate"));
if(await p.inputValue("#fxRate")!=="4")errs.push("rate not saved");
await b.close();console.log("errors:",JSON.stringify(errs));})();
